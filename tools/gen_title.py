#!/usr/bin/env python3
"""Packs the title screen's logo PNG into `mixins/clickgui/title_data.rs`.

    python3 native/clickgui/tools/gen_title.py ["~/minceraft(1).png"]

The bytes are embedded as-is (title_data.rs is ~4 bytes per byte of PNG) and
decoded once at run time by `clickgui_title_logo` with the game's own PNG
decoder, so the mod carries no decoder of its own.
"""
import struct
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE.parent / "mixins" / "clickgui" / "title_data.rs"
DEFAULT = Path.home() / "minceraft(1).png"


def size(data):
    if data[:8] != b"\x89PNG\r\n\x1a\n":
        sys.exit("not a PNG")
    width, height = struct.unpack(">II", data[16:24])
    return width, height


def entries(data, per_line=24):
    lines = []
    for start in range(0, len(data), per_line):
        chunk = data[start:start + per_line]
        lines.append("    " + ", ".join(str(b) for b in chunk) + ",")
    return "\n".join(lines)


def main():
    source = Path(sys.argv[1]).expanduser() if len(sys.argv) > 1 else DEFAULT
    data = source.read_bytes()
    width, height = size(data)
    text = (
        "// The title screen's logo (`minceraft.png`), as PNG bytes. `clickgui_title_logo`\n"
        "// decodes it once and draws it 256x64 GUI pixels over the vanilla logo.\n"
        "// Generated by `native/clickgui/tools/gen_title.py`; do not edit by hand.\n"
        "\n"
        f"pub(super) const WIDTH: u32 = {width};\n"
        f"pub(super) const HEIGHT: u32 = {height};\n"
        f"pub(super) const PNG: &[u8] = &[\n{entries(data)}\n];\n"
    )
    OUT.write_text(text)
    print(f"{OUT}: {width}x{height}, {len(data)} bytes")


if __name__ == "__main__":
    main()
